const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const ctx=vm.createContext({console});
vm.runInContext(fs.readFileSync('apps-script/Code.gs','utf8'),ctx);
const run=s=>JSON.parse(vm.runInContext('JSON.stringify('+s+')',ctx));
const state={primary_board_rotation:12,workable_board_rotation:3,board_rotation:99,pending_review:{keep:1}};
ctx.fixture=state;const before=JSON.stringify(state);
let r=run('rotationSummary(Array(300),Array(74),78,2,fixture)');
assert.equal(r.primary.nominal_runs_per_visit_cycle,4);
assert.equal(r.workable.nominal_runs_per_visit_cycle,37);
assert.equal(r.workable.next_offset,3);
assert.equal(r.completion_guaranteed,false);
assert.equal(JSON.stringify(state),before);
r=run('rotationSummary(Array(300),Array(74),0,1,{})');
assert.equal(r.primary.nominal_runs_per_visit_cycle,null);
assert.equal(r.workable.nominal_runs_per_visit_cycle,74);
r=run('rotationSummary([],[],0,0,{})');
assert.equal(r.primary.nominal_runs_per_visit_cycle,0);
assert.equal(r.workable.next_offset,0);
console.log('PASS rotation capacity: separate pools, zero slots, empty pools, no state mutation');
