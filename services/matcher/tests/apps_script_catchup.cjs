const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const ctx=vm.createContext({console});
for(const f of ['ScoringConfig.gs','Scoring.gs','Code.gs'])vm.runInContext(fs.readFileSync('apps-script/'+f,'utf8'),ctx);
const run=s=>vm.runInContext(s,ctx);
const now=Date.parse('2026-10-15T12:00:00Z');ctx.now=now;
const status=(published,days=30)=>{ctx.published=published;return run(`discoveryWindow({published_at:published},${days},now).date_status`);};
assert.equal(status('2026-09-15T12:00:00Z'),'within_window');
assert.equal(status('2026-09-15T11:59:59Z'),'outside_window');
assert.equal(status('2026-09-01T12:00:00Z',60),'within_window');
assert.equal(status('2026-08-16T12:00:00Z',60),'within_window');
assert.equal(status('2026-08-16T11:59:59Z',60),'outside_window');
assert.equal(status('2026-09-15T14:00:00+02:00'),'within_window');
assert.equal(status('2026-09-15 12:00:00'),'within_window');
for(const d of ['',null,'yesterday','2026-02-30','2026-10-16','2026-13-01'])assert.equal(status(d),'unknown');
run(`var clock=Date.now;Date.now=()=>now;var b={provider:'remotive',name:'Remotive'};
var lead=leadFrom({id:1,company_name:'Fictional',title:'Head of Operations',url:'https://remotive.com/remote-jobs/business/fictional-1',candidate_required_location:'Worldwide',description:'A'.repeat(250),publication_date:'2026-09-01T12:00:00Z'},b);
var state={legacy:'preserve'};discoverFeed=()=>({jobs:[Object.assign({},lead)],pages:1,truncated:false});
var result=marketDiscovery(new Set(),{},state,{DISCOVERY_CATCHUP_DAYS:'30'});`);
assert.equal(run('result.leads.length'),0);
assert.equal(run('result.catchup.outside_window_retained'),1);
assert.equal(run('Object.keys(state.discovery_review).length'),1);
assert.equal(run('state.legacy'),'preserve');
run(`var first=state.discovery_review['remotive:1'].source_first_seen_at;now+=86400000;result=marketDiscovery(new Set(),{},state,{DISCOVERY_CATCHUP_DAYS:'60'});`);
assert.equal(run('result.leads.length'),1);
assert.equal(run('result.leads[0].source_first_seen_at'),run('first'));
assert.equal(run('result.leads[0].source_last_seen_at'),new Date(now+86400000).toISOString());
assert.equal(run('result.leads[0].employer_live_verified'),false);
assert.equal(run('result.catchup.exhaustive'),false);
// Absence/outage does not close a retained lead or invent a last-seen time.
run(`var last=state.discovery_review['remotive:1'].source_last_seen_at;discoverFeed=()=>{throw new Error('Outage');};result=marketDiscovery(new Set(),{},state,{DISCOVERY_CATCHUP_DAYS:'60'});`);
assert.equal(run('result.leads.length'),1);
assert.equal(run('result.leads[0].source_last_seen_at'),run('last'));
run(`marketDiscovery(new Set(identities(lead)),{},state,{DISCOVERY_CATCHUP_DAYS:'60'});Date.now=clock;`);
assert.equal(run('Object.keys(state.discovery_review).length'),0);
console.log('PASS catchup boundaries, UTC, invalid/unknown dates, retained queue, 30/60 windows, first/last seen, outage and tracker dedup');
// Previously retained leads can teach a supported board without a fresh feed.
run(`var retained=Object.assign({},lead,{employer_references:['https://jobs.ashbyhq.com/fictional-catchup/abc','https://jobs.ashbyhq.com.evil.example/unsafe/abc'],published_at:''});
state={discovery_review:{old:retained}};discoverFeed=()=>({jobs:[],pages:1,truncated:false});
result=marketDiscovery(new Set(),{},state,{});`);
assert.equal(run('result.new_boards'),1);
assert.equal(run('state.discovered_boards[0].board'),'fictional-catchup');
assert.equal(run('result.catchup.unknown_date'),1);
assert.equal(run('result.leads[0].employer_live_verified'),false);
run('result=marketDiscovery(new Set(),{},state,{});');
assert.equal(run('result.new_boards'),0);
assert.equal(run('state.discovered_boards.length'),1);
run(`state={discovery_review:{old:Object.assign({},lead,{source_first_seen_at:null,source_last_seen_at:'2026-10-14T12:00:00Z'})}};discoverFeed=()=>({jobs:[Object.assign({},lead)],pages:1,truncated:false});result=marketDiscovery(new Set(),{},state,{DISCOVERY_CATCHUP_DAYS:'60'});`);
assert.equal(run('result.leads[0].source_first_seen_at'),null);
